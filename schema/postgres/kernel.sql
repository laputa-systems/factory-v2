-- PostgreSQL 18 canonical schema. This is a fresh authoritative ledger; no prototype data is imported.
-- Table definitions are dependency-neutral so the complete foreign-key contract can be named and installed after all tables exist.
CREATE TABLE principals (
    principal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    principal_kind BIGINT NOT NULL CHECK (principal_kind IN (1, 2, 3, 4)),
    display_name TEXT NOT NULL UNIQUE,
    active BOOLEAN NOT NULL
);
CREATE TABLE societies (
    society_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    lifecycle_state BIGINT NOT NULL CHECK (lifecycle_state IN (1, 2))
);
CREATE TABLE office_contracts (
    office_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_kind BIGINT NOT NULL UNIQUE CHECK (office_kind = 1),
    installed_by_command_id BIGINT NOT NULL
);
CREATE TABLE applications (
    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_identity TEXT NOT NULL UNIQUE,
    application_name TEXT NOT NULL UNIQUE,
    created_by_command_id BIGINT NOT NULL
);
-- A replaceable actor attempt is not an Office session.  These named receipt
-- relations preserve the one task prompt, its peer accounting, and disposal
-- without giving an actor the reusable Root Authority Office contract.
