CREATE TABLE pi_task_attempt_terminal_receipts (
    pi_task_attempt_terminal_receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_attempt_id BIGINT NOT NULL UNIQUE,
    pi_task_attempt_prompt_authorization_id BIGINT NOT NULL UNIQUE,
    native_child_id BIGINT NOT NULL,
    pi_session_id BIGINT NOT NULL,
    correlation_identity TEXT NOT NULL,
    terminal_evidence_kind BIGINT NOT NULL CHECK (terminal_evidence_kind IN (1, 2)),
    agent_settled_sequence BIGINT CHECK (agent_settled_sequence > 0),
    final_accounting_sequence BIGINT NOT NULL CHECK (final_accounting_sequence > 0),
    settled_sequence BIGINT NOT NULL CHECK (settled_sequence > 0),
    final_usage_receipt_id BIGINT,
    final_usage_failure_id BIGINT,
    disposition BIGINT NOT NULL CHECK (disposition BETWEEN 1 AND 6),
    assistant_outcome BIGINT NOT NULL CHECK (assistant_outcome BETWEEN 1 AND 6),
    transcript_disposition BIGINT NOT NULL CHECK (transcript_disposition = 1),
    recorded_by_command_id BIGINT NOT NULL,
    CHECK (((terminal_evidence_kind = 1 AND agent_settled_sequence IS NOT NULL
                AND agent_settled_sequence < final_accounting_sequence)
            OR (terminal_evidence_kind = 2 AND agent_settled_sequence IS NULL))
       AND final_accounting_sequence + 1 = settled_sequence),
    CHECK ((final_usage_receipt_id IS NOT NULL AND final_usage_failure_id IS NULL)
        OR (final_usage_receipt_id IS NULL AND final_usage_failure_id IS NOT NULL)),
    CHECK ((terminal_evidence_kind = 1 AND assistant_outcome BETWEEN 1 AND 4)
        OR (terminal_evidence_kind = 2 AND assistant_outcome IN (5, 6))),
    CHECK (terminal_evidence_kind != 2 OR final_usage_receipt_id IS NOT NULL),
    CHECK ((disposition = 1 AND assistant_outcome = 1)
        OR (disposition = 2 AND assistant_outcome = 2)
        OR (disposition = 3 AND assistant_outcome = 3)
        OR (disposition = 4 AND assistant_outcome = 4)
        OR (disposition = 5 AND assistant_outcome = 5)
        OR (disposition = 6 AND assistant_outcome = 6))
);
