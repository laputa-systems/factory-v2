-- Explicitly advance identity sequences after BY DEFAULT bootstrap inserts.
DO $$
DECLARE
    identity_row RECORD;
    next_value BIGINT;
BEGIN
    FOR identity_row IN
        SELECT table_name, column_name
        FROM information_schema.columns
        WHERE table_schema = current_schema() AND is_identity = 'YES'
    LOOP
        EXECUTE format('SELECT COALESCE(MAX(%I), 0) + 1 FROM %I', identity_row.column_name, identity_row.table_name)
            INTO next_value;
        EXECUTE format('ALTER TABLE %I ALTER COLUMN %I RESTART WITH %s', identity_row.table_name, identity_row.column_name, next_value);
    END LOOP;
END;
$$;
