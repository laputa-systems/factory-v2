    charged_micros BIGINT NOT NULL DEFAULT 0 CHECK (charged_micros >= 0),
    reservation_state BIGINT NOT NULL CHECK (reservation_state IN (1, 2, 3)),
    reserved_by_command_id BIGINT NOT NULL,
    reconciled_by_command_id BIGINT
